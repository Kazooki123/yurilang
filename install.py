def main():
    parser = argparse.ArgumentParser(description="YuriLang Installer")
    parser.add_argument(
        "--user",
        action="store_true",
        help="Install to user directory (no sudo/admin required)",
    )
    parser.add_argument("--uninstall", action="store_true", help="Uninstall YuriLang")
    args = parser.parse_args()

    banner()

    if args.uninstall:
        uninstall()
        return

    # detect OS
    system = platform.system()
    is_termux = "com.termux" in os.environ.get(
        "PREFIX", ""
    ) or "com.termux" in os.environ.get("HOME", "")

    check_python()
    check_dependencies()
    check_nasm()

    p(f"\nDetected OS: {system}", PURPLE)
    if is_termux:
        p("  📱 Termux detected!", PINK)

    # install
    if is_termux:
        path = install_termux()
    elif system == "Windows":
        path = install_windows(user_install=args.user)
    else:
        path = install_unix(user_install=args.user)

    success_message(path)


if __name__ == "__main__":
    main()
